#!/usr/bin/env python3
"""Split independent IIR channels across lanes, preserving original DF arithmetic."""
from pathlib import Path
import hashlib,json,struct,subprocess,sys,tempfile
root=Path(__file__).resolve().parents[2];base=root/'third_party/spektrafilm_android';p=base/'patches'
src=base/'engine/gpu/halation_scatter.comp'
assert hashlib.sha256(src.read_bytes()).hexdigest()==json.loads((base/'UPSTREAM_SHA256.json').read_text())[str(src.relative_to(root))]
s=src.read_text();a=s.index('    const uint line = gl_WorkGroupID.x');b=s.index('\n  const uvec2 gid',a)
s=s[:a]+'''    // LutCam local change: independent (column,channel) lanes. Same DF math.
    const uint lane=gl_WorkGroupID.x*kThreadsPerGroup+gl_LocalInvocationIndex;
    const uint line=lane/3u,c=lane%3u;
    if(line>=params.width || params.height==0u)return;
    const uint slot=blurSlot();
    if(blurIsIir(slot,c)) {
      if(params.operation==kOpLineInPlace)iirColumnInPlace(line,params.height,slot,c);
      else iirColumnAccumulate(line,params.height,slot,c,blurWeight(slot,c));
    }
    return;
  }
''' +s[b:]
(p/'spatial_parallel.comp').write_text(s)
with tempfile.TemporaryDirectory() as t:
 b=Path(t)/'s.spv';subprocess.run([sys.argv[1],'--target-env=vulkan1.0','-O',str(p/'spatial_parallel.comp'),'-o',str(b)],check=True);data=b.read_bytes()
w=struct.unpack('<'+'I'*(len(data)//4),data)
h='// Generated by build_spatial_parallel_shader.py; GPLv3; see GLSL notices.\n#pragma once\n#include <cstdint>\nstatic const uint32_t kLutcamSpatialParallelSpv[]={\n'
h+=''.join('    '+','.join(f'0x{x:08x}' for x in w[i:i+8])+',\n' for i in range(0,len(w),8))+'};\n';(p/'spatial_parallel_spv.h').write_text(h)
(p/'spatial_shader_sha256.json').write_text(json.dumps({'glsl':hashlib.sha256((p/'spatial_parallel.comp').read_bytes()).hexdigest(),'spirv':hashlib.sha256(data).hexdigest()},indent=2)+'\n');print('Spatial shader',len(data),'bytes')
