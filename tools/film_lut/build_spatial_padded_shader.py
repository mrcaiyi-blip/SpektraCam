#!/usr/bin/env python3
"""GPLv3: pad the original 32x32 shared transpose tiles by one float."""
from pathlib import Path
import hashlib,json,struct,subprocess,sys,tempfile
root=Path(__file__).resolve().parents[2];p=root/'third_party/spektrafilm_android/patches'
src=p/'spatial_parallel.comp'
assert hashlib.sha256(src.read_bytes()).hexdigest()==json.loads((p/'spatial_shader_sha256.json').read_text())['glsl']
s=src.read_text();anchor='shared float tile[3][32][32];';assert s.count(anchor)==1
s=s.replace(anchor,'// LutCam: one padding element per row; all pixel indices/operations unchanged.\nshared float tile[3][32][33];')
(p/'spatial_padded.comp').write_text(s)
with tempfile.TemporaryDirectory() as t:
 b=Path(t)/'s.spv';subprocess.run([sys.argv[1],'--target-env=vulkan1.0','-O',str(p/'spatial_padded.comp'),'-o',str(b)],check=True);data=b.read_bytes()
w=struct.unpack('<'+'I'*(len(data)//4),data)
h='// Generated by build_spatial_padded_shader.py; GPLv3; see GLSL notices.\n#pragma once\n#include <cstdint>\nstatic const uint32_t kLutcamSpatialPaddedSpv[]={\n'
h+=''.join('    '+','.join(f'0x{x:08x}' for x in w[i:i+8])+',\n' for i in range(0,len(w),8))+'};\n';(p/'spatial_padded_spv.h').write_text(h)
(p/'spatial_padded_sha256.json').write_text(json.dumps({'glsl':hashlib.sha256((p/'spatial_padded.comp').read_bytes()).hexdigest(),'spirv':hashlib.sha256(data).hexdigest()},indent=2)+'\n');print('Padded transpose shader',len(data),'bytes')
